// Tr returns the translated string for a given key and language.
// Defaults to English if the language or key is missing.
func Tr(lang, key string) string {
	lang = strings.ToLower(lang)
	if _, ok := stringsDB[lang]; !ok {
		lang = "en"
	}
	dict := stringsDB[lang]
	if val, ok := dict[key]; ok {
		return val
	}
	// Fallback to EN
	if val, ok := stringsDB["en"][key]; ok {
		return val
	}
	return key
}
